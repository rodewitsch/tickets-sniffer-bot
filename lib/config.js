// Минимальный интервал между автоматическими циклами проверки (минуты).
export const CHECK_INTERVAL_MIN = 10;

// Бюджет запросов деталей событий за один цикл проверки.
//
// Бюджет ГЛОБАЛЬНЫЙ (на всю базу), но расходуется по «кошельку на чат»:
// см. planPerChatAllocation в lib/checker.js. Раньше он был единственным лимитом
// и при 20+ позициях и 10 чатах выбирался в ноль каждый цикл, из-за чего события
// могли не проверяться сутками.
//
// Значение 24 (было 12) по факту из check_log: при 21–22 позициях цикл просил
// ~15 детальных запросов и получал 8 (detail_denied=11, per_chat_denied=12 при
// спенде 4). Удвоение покрывает реальный спрос, при этом цикл по времени растёт
// незначительно (сейчас ~35–45 с при интервале 15–30 мин), а нагрузка на сайты
// остаётся «человеческой»: 24 запроса за 15 минут ≈ 1.6 в минуту.
export const DETAIL_BUDGET = 24;

// Сколько детальных запросов может потратить ОДИН чат за цикл (нижняя граница).
// Квота считается ПРОПОРЦИОНАЛЬНО числу активных позиций чата (см.
// planPerChatAllocation в lib/checker.js), а этот минимум гарантируется чату,
// если бюджета суммарно хватает. Один пользователь с 15 ключевиками не может
// съесть весь бюджет: его квота ограничена долей его позиций.
export const DETAIL_BUDGET_MIN_PER_CHAT = 1;

// Срок жизни кэша результатов поиска (см. lib/search-cache.js). Поиск отвечает
// на вопрос «какие события вообще существуют», а не «есть ли билеты», поэтому
// 10 минут устаревания безопасны: наличие проверяется отдельно по каждому
// событию.
export const SEARCH_CACHE_TTL_MS = 10 * 60 * 1000;

// Максимум записей в кэше поиска на источник (защита от роста памяти).
export const SEARCH_CACHE_MAX_ENTRIES = 500;

// Порядок обхода позиций задаёт чекер (см. byDebt в lib/checker.js): сначала
// те, кого откладывали дольше всех. Отдельный флаг не нужен — откатываться к
// случайному шаффлу больше нет смысла: именно он и приводил к «вечному» голоду
// части позиций.

// Через сколько часов перечитывать событие, которое ЕЩЁ НЕ в продаже и начнётся
// не скоро. Если до события больше RECHECK_PRESALE_HORIZON_DAYS, повторная
// проверка раз в сутки достаточна — месяц—два до старта продаж ничего не меняет,
// а такие события стабильно выедали бюджет. Внутри окна — обычный RECHECK_SECONDS.
export const RECHECK_PRESALE_HORIZON_DAYS = 14;

// Логирование цикла проверки (см. lib/checker-log.js).
// CHECK_LOG_LEVEL: 'off' | 'summary' (одна строка на цикл) | 'items' (+ строка на
// позицию при CHECK_LOG_ITEMS) | 'debug' (+ причина каждого пропуска).
// В docker-compose настраивается переменной окружения CHECK_LOG_LEVEL.
export const CHECK_LOG_LEVEL = process.env.CHECK_LOG_LEVEL || 'summary';
// Печатать ли строку по каждой позиции (только при уровне 'items'/'debug').
export const CHECK_LOG_ITEMS = process.env.CHECK_LOG_ITEMS === '1';
// Медленная позиция: если проверка дольше этого порога — пишем warning с
// причиной (обычно это зависший запрос к билетному сайту).
export const SLOW_ITEM_MS = Number(process.env.SLOW_ITEM_MS || 10000);

// Часть DETAIL_BUDGET, зарезервированная под события площадок и обход площадок
// из поиска. Без резерва идущие в списке раньше позиции-ключевики выедали весь
// бюджет, и хвост списка (в т.ч. все площадки) не проверялся никогда.
// Площадки — самая «громоздкая» ветка (десятки событий на площадь), поэтому
// им выделяется треть бюджета; остальное — обычным позициям. Нижняя граница в 1:
// при крошечном DETAIL_BUDGET «треть» округлилась бы до нуля, и обход площадок
// молча не начинался бы ни разу (а счётчики прерывания врали бы о причине).
export const VENUE_BUDGET_RESERVE = Math.max(1, Math.floor(DETAIL_BUDGET / 3));

// Максимум городских проверок внутри ОДНОЙ позиции события (защита от «всех городов»,
// когда городов в каталоге станет много).
