// Режим «написать владельцу» из раздела Помощь.
//
// Когда пользователь нажимает «✍️ Сообщить об ошибке / пожелание», чат ставится в
// режим ввода обращения: следующее текстовое сообщение пересылается владельцу
// (STATS_CHAT_ID), а не трактуется как ключевое слово для отслеживания.
//
// Состояние хранится В ПАМЯТИ модуля. Все вебхуки обрабатывает единый процесс
// `bot` (server.js, последовательная очередь апдейтов), поэтому между апдейтами
// состояние стабильно. Минус — сбрасывается при перезапуске бота, что приемлемо
// (режим одноразовый: пользователь пишет одно сообщение или жмёт «Отмена»).

// Активные чаты в режиме ввода обращения.
const active = new Set();

export function feedbackSession(chatId) {
  return active.has(chatId);
}

export function startFeedback(chatId) {
  active.add(chatId);
}

export function clearFeedback(chatId) {
  active.delete(chatId);
}
